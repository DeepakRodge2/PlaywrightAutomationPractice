//dowhile loop
//dowhile loop is used to execute a block of code repeatedly until a specified condition is true. It consists of two parts: code to be executed and condition.
//syntax: dowhile{ //code to be executed }while(condition);
//example: print numbers from 1 to 10
var i=1;
do
{
    console.log(i);
    i++;
}while(i<=10);
