//foreach loop
//foreach loop is used to execute a block of code for each element in an array. It takes a callback function as an argument, which is executed for each element in the array.
//syntax: array.forEach(function(currentValue, index, arr), thisValue)
//example: print each element in an array
var arr=[1,2,3,4,5];
arr.forEach((a,b,)=>{
    console.log(b,a,a**2);
})